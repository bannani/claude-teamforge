// Employees with their own model run as real Copilot sub-agents. Copilot only
// loads custom agents from the project's `.github/agents/` folder (probed on
// CLI 1.0.109: --add-dir does not load them), so TeamForge keeps one generated
// file there per such employee, and removes it when the model goes back to default.

import { appendFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DEPARTMENTS, ROLE_CATALOG } from '../roles.mjs';
import { charter } from './skills.mjs';

export const AGENT_PREFIX = 'teamforge-';
const MARK = '<!-- generated by TeamForge: edits are overwritten -->';
const EXCLUDE = '.github/agents/teamforge-*.agent.md';

export const isModelName = (s) => typeof s === 'string' && /^[\w.:-]{1,64}$/.test(s);
export const agentName = (roleId) => `${AGENT_PREFIX}${roleId}`;
export const roleOfAgent = (name) => {
  const id = String(name || '').startsWith(AGENT_PREFIX) ? String(name).slice(AGENT_PREFIX.length) : null;
  return ROLE_CATALOG.some((r) => r.id === id) ? id : null;
};

export function agentFile(role, model) {
  const dept = DEPARTMENTS.find((d) => d.id === role.department)?.name || role.department;
  return `---
name: ${agentName(role.id)}
description: ${JSON.stringify(`TeamForge ${role.title} (${dept}). ${role.mission}`)}
model: ${model}
---
${MARK}

You are the **${role.title}** of the TeamForge company (${dept} department).

${role.mission}

Your responsibilities:
${role.responsibilities.map((r) => `- ${r}`).join('\n')}

You deliver: ${role.deliverable}.
${charter(role.id) ? `\n## Your charter\n${charter(role.id)}\n` : ''}
Rules:
- Do exactly the task the CEO gave you — nothing more. You do not talk to the client.
- The workflow decides what can be written or run. If a write or a command is denied, do not look for a way around it: stop and say what you needed.
- Report failures as they are, with the real output.
- End with a short report: what you did, files changed, how you checked it, and what is left.
`;
}

// models: { roleId: modelName }. Returns the role ids that now have an agent file.
export function syncAgentFiles(project, models) {
  const dir = join(project, '.github', 'agents');
  const wanted = ROLE_CATALOG.filter((r) => r.id !== 'ceo' && isModelName(models[r.id]));
  const keep = new Set(wanted.map((r) => `${agentName(r.id)}.agent.md`));
  if (existsSync(dir)) {
    for (const f of readdirSync(dir)) {
      // only files TeamForge generated are ever removed
      if (f.startsWith(AGENT_PREFIX) && f.endsWith('.agent.md') && !keep.has(f)
        && readFileSync(join(dir, f), 'utf8').includes(MARK)) rmSync(join(dir, f));
    }
  }
  if (!wanted.length) return [];
  mkdirSync(dir, { recursive: true });
  for (const role of wanted) writeFileSync(join(dir, `${agentName(role.id)}.agent.md`), agentFile(role, models[role.id]));
  // keep the generated files out of the project's commits, without touching tracked files
  const exclude = join(project, '.git', 'info', 'exclude');
  if (existsSync(join(project, '.git', 'info')) && !(existsSync(exclude) && readFileSync(exclude, 'utf8').includes(EXCLUDE))) {
    appendFileSync(exclude, `\n# TeamForge sub-agents (generated)\n${EXCLUDE}\n`);
  }
  return wanted.map((r) => r.id);
}
